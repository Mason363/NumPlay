#!/usr/bin/env python3
"""NumView's reading fonts: Nunito (as the launcher's, tools/fontgen.py) at three sizes for a book's text and three
for its headings, with the letters books use beyond ASCII (Latin-1, curly quotes, dashes, the ellipsis...).

Writes src/read_font.c. Their code points beyond ASCII go in nv_extra, sorted, in the order of their glyphs after the
95 ASCII ones; tools/mediapack.py keeps a book to them (READ_EXTRA below is the list both use).

Usage: readfont.py [out.c]
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[2] / "tools"))
import fontgen  # noqa: E402

# Latin-1's letters and signs, then typography
READ_EXTRA = sorted(set(range(0xA1, 0x100)) - {0xAD} | {
    0x2018, 0x2019, 0x201C, 0x201D, 0x2013, 0x2014, 0x2026, 0x2022, 0x2122, 0x20AC, 0x0152, 0x0153, 0x2032, 0x2033})
# name, cap height in pixels, weight, extra spacing (1/4 px)
SPECS = [
    ("nv_read_s", 8, 600, 1), ("nv_read_m", 10, 560, 1), ("nv_read_l", 12, 540, 0),
    ("nv_head_s", 10, 850, 0), ("nv_head_m", 12, 850, 0), ("nv_head_l", 14, 850, 0),
]


def main(out):
    lines = ["/* Generated by games/numview/tools/readfont.py from Nunito (SIL Open Font License 1.1). */",
             '#include "read_font.h"', "",
             f"const uint16_t nv_extra[{len(READ_EXTRA)}] = {{" + ", ".join(str(c) for c in READ_EXTRA) + "};",
             f"const int nv_extra_count = {len(READ_EXTRA)};", ""]
    total = 0
    for name, cap, weight, spacing in SPECS:
        f = fontgen.load(cap, weight)
        data, glyphs, asc, desc = bytearray(), [], 0, 0
        for c in list(range(32, 127)) + READ_EXTRA:
            g, adv = fontgen.glyph(f, chr(c), spacing * fontgen.UP / 4)
            if g is None:
                glyphs.append((0, 0, 0, 0, adv, len(data)))
                continue
            q, ox, oy = g
            h, w = q.shape
            if c < 127:
                asc, desc = max(asc, -oy), max(desc, h + oy)
            flat = q.flatten().tolist() + [0] * (q.size % 2)
            off = len(data)
            data += bytes(flat[i] | flat[i + 1] << 4 for i in range(0, len(flat), 2))
            glyphs.append((w, h, ox, oy, adv, off))
        total += len(data) + 7 * len(glyphs)
        lines.append(f"static const uint8_t {name}_data[{len(data)}] = {{")
        lines += ["  " + ",".join(str(b) for b in data[i:i + 24]) + "," for i in range(0, len(data), 24)]
        lines.append("};")
        lines.append(f"static const np_glyph_t {name}_glyphs[{len(glyphs)}] = {{")
        lines += [f"  {{{w}, {h}, {ox}, {oy}, {adv}, {off}}}," for w, h, ox, oy, adv, off in glyphs]
        lines.append("};")
        lines.append(f"const np_font_t {name} = {{32, {len(glyphs)}, {asc}, {desc}, {name}_glyphs, {name}_data}};")
        lines.append("")
        print(f"{name}: cap {cap}px, ascent {asc}, descent {desc}, {len(data)} bytes of glyphs")
    Path(out).write_text("\n".join(lines))
    print(f"total {total} bytes")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else str(HERE.parent / "src" / "read_font.c"))
