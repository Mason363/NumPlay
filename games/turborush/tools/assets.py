"""Convert original artwork into flash-only, 6-bit indexed game assets.
No image decoder or full-size framebuffer is needed on the calculator.
"""
from pathlib import Path
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
def array(f,name,values,kind='uint8_t'):
 f.write('static const '+kind+' '+name+'[]={\n')
 for i in range(0,len(values),24):f.write(','.join(str(x)for x in values[i:i+24])+',\n')
 f.write('};\n')
def pack(pixels):
 out=[];bits=0;n=0
 for p in pixels:
  bits|=p<<n;n+=6
  while n>=8:out.append(bits&255);bits>>=8;n-=8
 if n:out.append(bits)
 return out+[0]
def main():
 source=Image.open(ROOT/'assets/panoramas.png').convert('RGB');w,h=source.size
 with (ROOT/'src/art.h').open('w')as f:
  f.write('/* Generated by tools/assets.py. Original art: assets/README.md. */\n')
  for i in range(4):
   panel=source.crop((0,h*i//4,w,h*(i+1)//4)).resize((400,100),Image.Resampling.LANCZOS)
   q=panel.quantize(colors=64,method=Image.Quantize.MEDIANCUT,dither=Image.Dither.NONE);pal=q.getpalette()[:192]
   array(f,'bg%d_palette'%i,[(pal[j]&248)<<8|(pal[j+1]&252)<<3|pal[j+2]>>3 for j in range(0,192,3)],'color_t')
   array(f,'bg%d_pixels'%i,pack(q.getdata()))
  source=Image.open(ROOT/'assets/cars.png').convert('RGBA');w,h=source.size;sprites=[]
  for row in range(2):
   for col in range(3):
    tile=source.crop((w*col//3,h*row//2,w*(col+1)//3,h*(row+1)//2))
    box=tile.getchannel('A').point(lambda a:255 if a>=128 else 0).getbbox();tile=tile.crop(box);tile.thumbnail((94,60),Image.Resampling.LANCZOS)
    canvas=Image.new('RGBA',(96,64));canvas.paste(tile,((96-tile.width)//2,63-tile.height));sprites.append(canvas)
  colors=[rgb[:3]for tile in sprites for rgb in tile.getdata()if rgb[3]>=128]
  training=Image.new('RGB',(len(colors),1));training.putdata(colors);palette=training.quantize(colors=63,method=Image.Quantize.MEDIANCUT,dither=Image.Dither.NONE)
  values=palette.getpalette();palette.putpalette(values[:189]+values[:3]*(256-63))
  rgb=palette.getpalette()[:189];rgb+= [0]*(192-len(rgb))
  paints=[(223,32,46),(255,202,59),(36,121,213),(48,186,128),(242,240,222),(166,110,224)]
  for k,paint in enumerate(paints):
   native=[]
   for j in range(64):
    r,g,b=rgb[j*3:j*3+3]
    if r>g*1.6 and r>b*1.5 and g<145:
     bright=max(r,g,b)/255;shine=min(g,b)*.35;r,g,b=[min(255,int(x*bright+shine))for x in paint]
    native.append((r&248)<<8|(g&252)<<3|b>>3)
   array(f,'car_palette%d'%k,native,'color_t')
  for i,tile in enumerate(sprites):
   q=tile.convert('RGB').quantize(palette=palette,dither=Image.Dither.NONE)
   pixels=[(idx if idx<63 else 0)if rgba[3]>=128 else 63 for idx,rgba in zip(q.getdata(),tile.getdata())]
   array(f,'car%d_pixels'%i,pack(pixels))
  source=Image.open(ROOT/'assets/scenery.png').convert('RGBA');w,h=source.size
  for i in range(8):
   edges=([0,.273,.501,.794,1]if i<4 else[0,.25,.46,.794,1]);col=i%4;row=i//4
   tile=source.crop((int(w*edges[col]),h*row//2,int(w*edges[col+1]),h*(row+1)//2))
   box=tile.getchannel('A').point(lambda a:255 if a>=128 else 0).getbbox();tile=tile.crop(box);tile.thumbnail((62,110),Image.Resampling.LANCZOS)
   canvas=Image.new('RGBA',(64,112));canvas.paste(tile,((64-tile.width)//2,111-tile.height))
   colors=[rgba[:3]for rgba in canvas.getdata()if rgba[3]>=128];training=Image.new('RGB',(len(colors),1));training.putdata(colors)
   palette=training.quantize(colors=63,method=Image.Quantize.MEDIANCUT,dither=Image.Dither.NONE);values=palette.getpalette();palette.putpalette(values[:189]+values[:3]*(256-63));q=canvas.convert('RGB').quantize(palette=palette,dither=Image.Dither.NONE)
   rgb=palette.getpalette()[:192];rgb+=[0]*(192-len(rgb));array(f,'scene%d_palette'%i,[(rgb[j]&248)<<8|(rgb[j+1]&252)<<3|rgb[j+2]>>3 for j in range(0,192,3)],'color_t')
   array(f,'scene%d_pixels'%i,pack([(idx if idx<63 else 0)if rgba[3]>=128 else 63 for idx,rgba in zip(q.getdata(),canvas.getdata())]))
if __name__=='__main__':main()
