#!/usr/bin/env python3
"""NumVisuals' font: Nunito (SIL Open Font License, see LICENSES/) as a signed distance field, so that one small set of
glyphs draws sharp, smooth letters at any size, with their shadows and glows (src/core.c).

Each printable ASCII glyph is rendered 8x supersampled with its cap height at BASE pixels, its distance to the outline
measured there (scipy's Euclidean distance transform), then sampled at the centre of each of its own pixels, SPREAD
pixels of margin round the ink: 128 on the outline, 255 SPREAD pixels inside, 0 SPREAD pixels outside. The output,
src/font_sdf.h, is committed: run this again only to change the font.

Usage: sdf.py [out.h]
"""
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFont
from scipy import ndimage

HERE = Path(__file__).resolve().parent
FONT = HERE.parents[2] / "tools" / ".fonts" / "Nunito.ttf"  # (tools/fontgen.py fetches it)
BASE = 20      # cap height, pixels
SPREAD = 4     # pixels of distance either side of the outline
UP = 8         # supersampling
WEIGHT = 600
FIRST, LAST = 32, 126


def load():
    for size in range(10, 400):
        f = ImageFont.truetype(str(FONT), size)
        f.set_variation_by_axes([WEIGHT])
        bb = f.getbbox("H", anchor="ls")
        if -bb[1] >= BASE * UP:
            return f
    raise SystemExit("size")


def glyph(f, ch):
    adv = f.getlength(ch) / UP
    bb = f.getbbox(ch, anchor="ls")
    if ch == " " or bb[2] <= bb[0]:
        return dict(adv=adv, x=0, y=0, w=0, h=0, px=b"")
    pad = SPREAD * UP + UP
    # the glyph on a canvas whose origin (baseline, pen) sits on a low-res pixel corner
    x0 = (bb[0] - pad) // UP * UP
    y0 = (bb[1] - pad) // UP * UP
    x1 = -(-(bb[2] + pad) // UP) * UP
    y1 = -(-(bb[3] + pad) // UP) * UP
    img = Image.new("L", (x1 - x0, y1 - y0), 0)
    ImageDraw.Draw(img).text((-x0, -y0), ch, font=f, fill=255, anchor="ls")
    ink = np.asarray(img) >= 128
    d_out = ndimage.distance_transform_edt(~ink)
    d_in = ndimage.distance_transform_edt(ink)
    sd = (np.where(ink, d_in - 0.5, -(d_out - 0.5))) / UP  # pixels, inside positive
    h, w = sd.shape[0] // UP, sd.shape[1] // UP
    cen = sd[UP // 2::UP, UP // 2::UP][:h, :w]
    v = np.clip(np.round(128 + cen * (127 / SPREAD)), 0, 255).astype(np.uint8)
    # crop the rows and columns that are all far outside
    rows = np.where(v.max(axis=1) > 0)[0]
    cols = np.where(v.max(axis=0) > 0)[0]
    v = v[rows[0]:rows[-1] + 1, cols[0]:cols[-1] + 1]
    return dict(adv=adv, x=x0 // UP + int(cols[0]), y=y0 // UP + int(rows[0]), w=v.shape[1], h=v.shape[0],
                px=v.tobytes())


def main():
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE.parent / "src" / "font_sdf.h"
    f = load()
    gs = [glyph(f, chr(c)) for c in range(FIRST, LAST + 1)]
    data = bytearray()
    rows = []
    for c, g in zip(range(FIRST, LAST + 1), gs):
        rows.append((len(data), g))
        data += g["px"]
    lines = [
        "/* Generated by tools/sdf.py: Nunito (SIL Open Font License) as a signed distance field, cap height "
        f"{BASE} px, {SPREAD} px each side of the outline (128 on it, more inside). */",
        "#define SDF_BASE %d" % BASE,
        "#define SDF_SPREAD %d" % SPREAD,
        "#define SDF_FIRST %d" % FIRST,
        "#define SDF_LAST %d" % LAST,
        "typedef struct {",
        "  uint16_t at;   /* where its pixels start in sdf_px */",
        "  uint8_t w, h;  /* its box */",
        "  int8_t x, y;   /* the box's top left from the pen on the baseline */",
        "  uint8_t adv;   /* the advance, 1/8 pixels */",
        "} sdf_glyph_t;",
        "static const sdf_glyph_t sdf_glyphs[%d] = {" % len(gs),
    ]
    for at, g in rows:
        lines.append("  {%d, %d, %d, %d, %d, %d}," % (at, g["w"], g["h"], g["x"], g["y"], round(g["adv"] * 8)))
    lines.append("};")
    lines.append("static const uint8_t sdf_px[%d] = {" % len(data))
    for i in range(0, len(data), 24):
        lines.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    lines.append("};")
    out.write_text("\n".join(lines) + "\n")
    print(f"{out}: {len(gs)} glyphs, {len(data)} bytes")


if __name__ == "__main__":
    main()
