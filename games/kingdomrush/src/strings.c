const char *tower_text(const char *key) {
  for (unsigned i = 0; i < sizeof tw / sizeof tw[0]; i++) {
    const char *a = tw[i][0], *b = key;
    while (*a && *a == *b) a++, b++;
    if (!*a && !*b) return tw[i][1];
  }
  return "";
}

